 */
function trk_demo_allowed(): bool
{
    global $dbhost;
    if (!in_array($dbhost ?? '', ['localhost', '127.0.0.1'], true)) {
        return false;
    }
    if (PHP_SAPI === 'cli') {
        return true;
    }
    return in_array($_SERVER['REMOTE_ADDR'] ?? '', ['127.0.0.1', '::1'], true);
}

